    public static class SwizzleUtility
    {
        public static Swizzle ParseSafe(string str)
        {
            if (string.IsNullOrEmpty(str))
            {
                return Swizzle._;
            }

            long result = 0;
            int position = 0;

            foreach (char ch in str)
            {
                char c = char.ToLowerInvariant(ch);

                int value = c switch
                {
                    '_' => 0,
                    'x' => 1,
                    'y' => 2,
                    'z' => 3,
                    'w' => 4,
                    _ => -1,
                };
                if(value >= 0)
                {
                    result |= (long)value << (position * 3);
                    position++;
                }
            }

            return (Swizzle)result;
        }
        public static Swizzle Parse(string str)
        {
            if (string.IsNullOrEmpty(str))
            {
                return Swizzle._;
            }

            long result = 0;
            int position = 0;

            foreach (char ch in str)
            {
                char c = char.ToLowerInvariant(ch);

                int value = c switch
                {
                    'x' => 1,
                    'y' => 2,
                    'z' => 3,
                    'w' => 4,
                    _ => 0,
                };

                result |= (long)value << (position * 3);
                position++;
            }

            return (Swizzle)result;
        }
    }
